package me.iLatteSoft.inventorySnapshot.repositories;

import com.zaxxer.hikari.HikariConfig;
import com.zaxxer.hikari.HikariDataSource;
import me.iLatteSoft.inventorySnapshot.InventorySnapshot;

import java.io.File;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.logging.Level;

@SuppressWarnings({"SqlNoDataSourceInspection", "SqlResolve"})
public class DatabaseManager {

    @FunctionalInterface
    public interface SQLFunction<T> {
        T apply(Connection connection) throws SQLException;
    }

    private static final int POOL_SIZE = 4;

    private final InventorySnapshot plugin;
    private final ExecutorService executor = Executors.newFixedThreadPool(POOL_SIZE, runnable -> {
        final Thread thread = new Thread(runnable, "Inventory-Snapshots-DB");
        thread.setDaemon(true);
        return thread;
    });

    private HikariDataSource dataSource;

    public DatabaseManager(final InventorySnapshot plugin) {
        this.plugin = plugin;
    }

    public boolean initialize() {
        final File dataFolder = plugin.getDataFolder();
        if (!dataFolder.exists() && !dataFolder.mkdirs()) {
            plugin.getLogger().log(Level.SEVERE, "Unable to create data folder folder.");
            return false;
        }

        final File databaseFile = new File(plugin.getDataFolder(), "database.db");

        final HikariConfig hikariConfig = new HikariConfig();
        hikariConfig.setPoolName("Inventory-Snapshots-DB");
        hikariConfig.setDriverClassName("org.h2.Driver");
        hikariConfig.setJdbcUrl("jdbc:h2:file:" + databaseFile.getAbsolutePath());
        hikariConfig.setMaximumPoolSize(POOL_SIZE);
        hikariConfig.setMinimumIdle(1);

        try {
            this.dataSource = new HikariDataSource(hikariConfig);
            this.createTables();
            plugin.getLogger().log(Level.INFO, "Database connection established.");
            return true;
        } catch (final Exception e) {
            plugin.getLogger().log(Level.SEVERE, "Database connection could not be established.", e);
            return false;
        }
    }

    private void createTables() throws SQLException {
        try (final Connection connection = this.dataSource.getConnection();
             final Statement statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE IF NOT EXISTS inventory_snapshots (
                                        id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        player_uuid  VARCHAR(36)  NOT NULL,
                                        player_name  VARCHAR(16)  NOT NULL,
                                        created_at   BIGINT       NOT NULL,            -- epoch millis
                                        reason       VARCHAR(32)  NOT NULL DEFAULT 'MANUAL',
                                        world        VARCHAR(64),
                                        x            DOUBLE PRECISION,
                                        y            DOUBLE PRECISION,
                                        z            DOUBLE PRECISION,
                                        inventory    CLOB         NOT NULL,            -- base64
                                        ender_chest  CLOB,                             -- base64
                                        total_xp     INT,
                                        health       DOUBLE PRECISION,
                                        food_level   INT,
                                        data_version INT          NOT NULL
                                    )
                    """);
            statement.execute("""
                    CREATE INDEX IF NOT EXISTS idx_snapshots_player_time
                    ON inventory_snapshots (player_uuid, created_at DESC)
                    """);
        }
    }

    public Connection getConnection() throws SQLException {
        return this.dataSource.getConnection();
    }

    public <T> CompletableFuture<T> supplyAsync(final SQLFunction<T> task) {
        return CompletableFuture.supplyAsync(() -> {
            try (final Connection connection = this.dataSource.getConnection()) {
                return task.apply(connection);
            } catch (final SQLException e) {
                plugin.getLogger().log(Level.SEVERE, "Supply async exception!", e);
                throw new RuntimeException(e);
            }
        }, this.executor);
    }

    public void close() {
        this.executor.shutdown();
        if (this.dataSource != null && !this.dataSource.isClosed()) {
            this.dataSource.close();
        }
    }

}
